import { cssVars, tokenVars } from "../foundation.mjs"

export function modeValues(foundation, mode) {
  return tokenVars(foundation.semantic[mode], "moira-")
}

export function cssOutputs(foundation, products) {
  const light = cssVars(modeValues(foundation, "light"))
  const dark = cssVars(modeValues(foundation, "dark"))
  const header = "/* Generated by @moirasia/design-system. Do not edit. */"
  const foundationCss = `${header}
@import "@fontsource/actor";
@import "@fontsource-variable/jetbrains-mono";

:root {
  color-scheme: light dark;
${cssVars(tokenVars(foundation.primitive, "moira-"))}
${light}
}

@media (prefers-color-scheme: dark) {
  :root {
${dark}
  }
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --moira-motion-fast: 0ms;
    --moira-motion-normal: 0ms;
    --moira-motion-deliberate: 0ms;
  }
}
`
  const outputs = new Map([["packages/ui-css/foundation.css", foundationCss]])
  for (const name of ["amove", "litemaptica", "exithibition", "openagent", "mini-nsw"]) {
    const mode = name === "mini-nsw" ? "light" : ["litemaptica", "exithibition"].includes(name) ? "dark" : null
    const domain = ["litemaptica", "mini-nsw"].includes(name) ? tokenVars(products[name].base.color, "moira-color-") : name === "exithibition" ? Object.fromEntries(Object.entries(tokenVars(products.exithibition.dark.color, "")).map(([role, value]) => [`moira-color-${["focus", "selected"].includes(role) ? "telemetry-" : ""}${role}`, value])) : {}
    const theme = mode ? `${header}
:root {
  color-scheme: ${mode};
${cssVars(modeValues(foundation, mode))}
${cssVars(domain)}
}
` : `${header}
/* Compatibility entrypoint; adaptive structural roles come from foundation.css. */
`
    outputs.set(`packages/ui-css/themes/${name}.css`, theme)
  }
  return outputs
}
