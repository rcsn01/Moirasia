import { dimensionPoints } from "../foundation.mjs"
import { colorToSrgb } from "../colors.mjs"
const identifier = value => value.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase())
const rgb = value => `RGB(${colorToSrgb(value).map(channel => Number(channel.toFixed(8))).join(", ")})`

export function swiftOutput(foundation, products) {
  const colors = ['canvas','surface','surfaceRaised','textPrimary','textMuted','textSubtle','border','borderStrong','control','controlHover','controlSelected','successSurface','successText','warningSurface','warningBorder','warningText','dangerSurface','dangerText','dangerAction','dangerActionHover','textOnDanger']
  const kebab = value => value.replace(/[A-Z]/g, letter => `-${letter.toLowerCase()}`)
  const semantic = (mode, name) => foundation.semantic[mode].color[kebab(name)].$value
  const constants = (name, group, transform) => `public enum ${name} {\n${Object.entries(group).filter(([key]) => !key.startsWith("$")).map(([key, node]) => `    public static let ${transform(key)}: ${name === "MoiraMotion" ? "Double" : "CGFloat"} = ${(name === "MoiraMotion" ? node.$value.value / 1000 : dimensionPoints(node, foundation))}`).join("\n")}\n}`
  const typeNames = {caption:'caption', small:'small', body:'body', bodyLarge:'body-large', titleSmall:'title-small', title:'title-medium', titleLarge:'title-large'}
  const types = Object.entries(typeNames).map(([name, role]) => `    public static func ${name}(weight: Font.Weight = .${name.startsWith("title") ? "semibold" : "regular"}, design: Font.Design = .default) -> Font {\n        #if canImport(UIKit)\n        // Semantic system styles scale with the SwiftUI Dynamic Type environment.\n        .system(.${foundation.native.typeStyles[role]}, design: design).weight(weight)\n        #else\n        .system(size: ${dimensionPoints(foundation.primitive.font.size[role], foundation)}, weight: weight, design: design)\n        #endif\n    }`).join("\n\n")
  const structural = {canvas:'canvas',surface:'surface',surfaceRaised:'surface-raised',textPrimary:'text-primary',textMuted:'text-muted',border:'border',windowBackground:'window-background'}
  const exithibition = {...Object.fromEntries(Object.entries(structural).map(([name, role]) => [name, foundation.semantic.dark.color[role].$value])), ...Object.fromEntries(Object.entries(products.exithibition.dark.color).filter(([name]) => !name.startsWith("$")).map(([name,node]) => [identifier(name),node.$value]))}
  return `// Generated by @moirasia/design-system. Do not edit.
import SwiftUI

#if canImport(AppKit)
import AppKit
#elseif canImport(UIKit)
import UIKit
#endif

public enum MoiraColor {
${colors.map(name => `    public static let ${name} = dynamic(light: ${rgb(semantic("light",name))}, dark: ${rgb(semantic("dark",name))})`).join("\n")}
}

${constants("MoiraSpace",Object.fromEntries(Object.entries(foundation.primitive.space).filter(([key]) => key !== "0")),key => `x${key}`)}

${constants("MoiraRadius",foundation.primitive.radius,identifier)}

${constants("MoiraControl",foundation.primitive.control.height,key => `${identifier(key)}Height`)}

${constants("MoiraMotion",foundation.primitive.motion,identifier)}

public enum MoiraType {
${types}
}

public enum MoiraExithibition {
${Object.entries(exithibition).map(([name,value]) => `    public static let ${name} = color(${rgb(value)})`).join("\n")}
}

private struct RGB {
    let red: Double
    let green: Double
    let blue: Double
    let opacity: Double

    init(_ red: Double, _ green: Double, _ blue: Double, _ opacity: Double = 1) {
        self.red = red
        self.green = green
        self.blue = blue
        self.opacity = opacity
    }
}

private func color(_ value: RGB) -> Color {
    Color(
        red: value.red,
        green: value.green,
        blue: value.blue,
        opacity: value.opacity
    )
}

private func dynamic(light: RGB, dark: RGB) -> Color {
    #if canImport(AppKit)
    return Color(
        nsColor: NSColor(name: nil) { appearance in
            let match = appearance.bestMatch(from: [.aqua, .darkAqua])
            let value = match == .darkAqua ? dark : light
            return NSColor(
                red: value.red,
                green: value.green,
                blue: value.blue,
                alpha: value.opacity
            )
        }
    )
    #elseif canImport(UIKit)
    return Color(
        uiColor: UIColor { traits in
            let value = traits.userInterfaceStyle == .dark ? dark : light
            return UIColor(
                red: value.red,
                green: value.green,
                blue: value.blue,
                alpha: value.opacity
            )
        }
    )
    #else
    return color(light)
    #endif
}
`
}
